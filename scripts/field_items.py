# ================================================================ burn
def burn():
    # A drop: a round bottom on a circle about (0, 3), drawn up to a point.
    cx, cy, r = 0.0, 3.0, 6.2
    tip = (0.0, -6.4)
    pts = [tip]
    for i in range(0, 15):
        a = math.radians(-35 + i * (250 / 14))  # from up-right, round the bottom, to up-left
        pts.append((cx + math.cos(a) * r, cy + math.sin(a) * r))
    drop = poly(pts)
    tongue = poly([(0, -6.2), (2.3, -1.6), (1.4, 1.2), (0, 0.4), (-1.6, 1.4), (-2.0, -1.4)])
    tongue_in = poly([(0, -3.6), (1.2, -0.6), (0, 0.6), (-1.1, -0.4)])
    parts = [
        part("drop", (0, 1.6), drop, "$oxblood.light", INK_THIN),
        part("glow", (-0.6, 3.8), ell(4.6, 4.8), "$ember"),
        part("heart", (-0.9, 4.4), ell(2.1, 2.3), "$gold"),
        part("tongue", (0.2, -5.4), tongue, "$ember", INK_HAIR),
        part("tongue_in", (0.2, -4.6), tongue_in, "$gold"),
        part("gloss", (-3.2, 0.2), ell(1.6, 0.9), "$silent@heavy", rot=-50),
    ]
    anims = {
        "idle": {
            "description": "the fire at its tip licking, the ember inside it pulsing",
            "duration": 0.9,
            "tracks": [
                track("tongue", "scale", [(0, 1), (0.3, 1.16), (0.6, 0.9), (1, 1)]),
                track("tongue", "rot", [(0, 0), (0.3, 6), (0.6, -5), (1, 0)]),
                track("tongue_in", "scale", [(0, 1), (0.3, 1.2), (0.6, 0.85), (1, 1)]),
                track("heart", "opacity", [(0, 0.85), (0.4, 1), (1, 0.85)]),
            ],
        }
    }
    return {
        "id": "ss.pickup.burn",
        "name": "Scent Burn",
        "description": (
            "Scent Burn, a field item: a gland like a drop of dark blood, an ember lit inside it and a tongue of fire "
            "licking out of its tip. Taken, a ring of fire goes out of you (ss.fx.flare). Was a vial of fire drawn in "
            "the game's own Graphics calls. Lit from the upper left, outlined in $ink at thin. "
            "Generated by scripts/field_items.py."
        ),
        "tags": ["pickup"],
        "size": [24, 24],
        "parts": parts,
        "animations": anims,
    }


if __name__ == "__main__":
    for doc in (breath(), hold(), burn()):
        path = os.path.join(OUT, doc["id"].replace(".", "-") + ".json")
        write_doc(doc, path)
        print("wrote", os.path.relpath(path))
