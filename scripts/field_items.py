"""The three field items — the breaths a run finds lying on the floor.

    python3 scripts/field_items.py    # rewrites apps/ss/assets/ss-pickup-{breath,hold,burn}.json

feelers drew these itself, in Graphics calls in its BootScene, as a horseshoe
magnet, a pocket watch and a vial of fire: three objects from a hardware shop
lying in a hive. They are the run's own breaths (the game's names: Deep
Breath, Held Breath, Scent Burn), so they are drawn as what the player
breathes with — organs, the way the food is a nutrient sac and the pulp a
lump of tissue — each in its effect's colour and each with its own idle:

  breath  twin lungs on a short pipe, aqua, swelling and emptying. Taken,
          every lump of pulp on the field is drawn in on the one breath.
  hold    a sealed sac crusted with frost, closed at the top; it does not
          breathe — that is the point — and only the ice on it glints.
          Taken, the horde freezes where it stands.
  burn    a gland like a drop of dark blood, an ember lit inside it and a
          tongue of fire licking out of its tip. Taken, a ring of fire goes
          out of you.

Lit from the upper left like the rest of the roster: the lit side is the
lighter value and the gloss sits up-left. Outlined in $ink at `thin`, the
pickups' own stroke (ss.pickup.food). 24×24, origin at the centre; the
game draws them at the size it drew its own (22–25 px across).
"""
import math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from rig import poly, ell, circ, rect, INK_THIN, INK_HAIR, write_doc

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "apps", "ss", "assets")


def part(pid, at, shape, fill, stroke=None, rot=None):
    p = {"id": pid, "at": [round(at[0], 2), round(at[1], 2)]}
    if rot is not None:
        p["rot"] = rot
    p["shape"] = shape
    p["fill"] = fill
    if stroke is not None:
        p["stroke"] = stroke
    return p


def track(pid, prop, keys):
    return {"part": pid, "prop": prop, "keys": [[k, v] for k, v in keys]}


